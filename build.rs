//! Records which PSCat revision this binary was built against, read from
//! `Cargo.lock` so the reported version can never drift from the real one,
//! and lists the vendored guide files (`guide/skills/`, see src/guide.rs) so
//! the binary embeds whatever `scripts/vendor-guide.py` copied.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=Cargo.lock");
    guide_files();
    let lock = fs::read_to_string("Cargo.lock").unwrap_or_default();
    let mut version = String::from("unknown");
    let mut source = String::from("unknown");
    let mut in_pscat = false;
    for line in lock.lines() {
        let line = line.trim();
        if line == "[[package]]" {
            in_pscat = false;
        } else if line == "name = \"pscat\"" {
            in_pscat = true;
        } else if in_pscat {
            if let Some(v) = line.strip_prefix("version = ") {
                version = v.trim_matches('"').to_string();
            } else if let Some(s) = line.strip_prefix("source = ") {
                source = s.trim_matches('"').to_string();
            }
        }
    }
    println!("cargo:rustc-env=PSCAT_VERSION={version}");
    println!("cargo:rustc-env=PSCAT_SOURCE={source}");
}

/// Writes `$OUT_DIR/guide_files.rs`: `GUIDE_FILES`, one
/// `(path under guide/skills, include_str!(...))` pair per file, sorted.
fn guide_files() {
    println!("cargo:rerun-if-changed=guide");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("guide/skills");
    let mut files = Vec::new();
    walk(&root, &mut files);
    files.sort();
    assert!(
        !files.is_empty(),
        "{} holds no files; run `python3 -I scripts/vendor-guide.py`",
        root.display()
    );
    let mut out = String::from("/// Generated by build.rs from guide/skills.\n");
    out.push_str("pub(crate) const GUIDE_FILES: &[(&str, &str)] = &[\n");
    for path in &files {
        let rel = path
            .strip_prefix(&root)
            .expect("under guide/skills")
            .to_str()
            .expect("UTF-8 guide path")
            .replace('\\', "/");
        let abs = path.to_str().expect("UTF-8 guide path");
        out.push_str(&format!("    ({rel:?}, include_str!({abs:?})),\n"));
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("guide_files.rs");
    fs::write(dest, out).expect("write guide_files.rs");
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            walk(&path, out);
        } else if path.is_file() {
            out.push(path);
        }
    }
}
